import { z } from "zod";

// 72 — жорсткий ліміт bcrypt(js) на довжину вхідного пароля (байти
// понад це просто мовчки відкидаються при хешуванні) — краще явно
// відхилити задовгий пароль з поясненням, ніж тихо обрізати його.
const email = z.string().trim().toLowerCase().email("Некоректний email");
const newPassword = z
  .string()
  .min(8, "Пароль має містити щонайменше 8 символів")
  .max(72, "Пароль занадто довгий (максимум 72 символи)");

export const registerSchema = z.object({
  email,
  password: newPassword,
});

// Логін навмисно НЕ перевіряє мінімальну довжину пароля — старий
// пароль міг бути коротшим за поточні правила ще до їх запровадження;
// довжину/складність контролюємо лише при СТВОРЕННІ пароля.
export const loginSchema = z.object({
  email,
  password: z.string().min(1, "Пароль обов'язковий"),
});
